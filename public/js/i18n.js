const I18N = { exact: {}, patterns: [] };
let LANG = 'az';

const norm = (s) => String(s).replace(/\s+/g, ' ').trim();

function setLang(lang) {
  LANG = LANGS.some((l) => l.id === lang) ? lang : 'az';
  const col = LANG === 'ru' ? 1 : LANG === 'en' ? 2 : 0;
  I18N.exact = {};
  I18N.patterns = [];
  if (!col) return;
  for (const row of DICT) {
    const key = norm(row[0]);
    const val = row[col];
    if (key.includes('{')) {
      const names = [];
      const src = key.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\{(\w+)\}/g, (_, n) => {
        names.push(n);
        return '(.+?)';
      });
      I18N.patterns.push({ re: new RegExp(`^${src}$`, 'u'), names, val });
    } else {
      I18N.exact[key] = val;
    }
  }
}

function lookup(s) {
  if (s in I18N.exact) return I18N.exact[s];
  for (const p of I18N.patterns) {
    const m = s.match(p.re);
    if (m) return p.val.replace(/\{(\w+)\}/g, (_, n) => { const v = m[p.names.indexOf(n) + 1]; return v === undefined ? '' : t(v); });
  }
  return null;
}

// Mətni seçilmiş dilə çevir; lüğətdə yoxdursa olduğu kimi qaytar
function t(text) {
  if (LANG === 'az' || text == null) return text;
  const s = norm(text);
  if (!s) return text;
  let r = lookup(s);
  if (r != null) return r;
  // Əvvəldəki emoji/işarələri və sondakı durğu işarələrini ayır: "💀 Bu gecə heç kim ölmədi!" -> "Bu gecə heç kim ölmədi"
  const m = s.match(/^([^\p{L}\p{N}]*)(.*?)([^\p{L}\p{N}]*)$/su);
  if (m && m[2] && (m[1] || m[3])) {
    // Əvvəlcə yalnız prefiksi at ("🗳️ Kimi qovuruq?" -> "Kimi qovuruq?"), sonra sonluğu da
    if (m[1]) {
      r = lookup(s.slice(m[1].length));
      if (r != null) return r ? `${m[1]}${r}` : '';
    }
    r = lookup(m[2]);
    if (r != null) return `${m[1]}${r}${r ? m[3] : ''}`.trim();
  }
  return text;
}

const TR_ATTRS = ['placeholder', 'aria-label', 'title'];

// Elementin içindəki bütün mətnləri və atributları tərcümə et (data-nt olanlar xaric)
function translateDom(root) {
  if (LANG === 'az' || !root) return;
  const skip = (el) => el && el.closest('[data-nt],script,style,textarea');
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  for (let n = walker.nextNode(); n; n = walker.nextNode()) nodes.push(n);
  for (const n of nodes) {
    const v = n.nodeValue;
    if (!/\p{L}/u.test(v) || skip(n.parentElement)) continue;
    const r = t(v);
    if (r !== v) {
      const lead = v.match(/^\s*/)[0];
      const trail = v.match(/\s*$/)[0];
      n.nodeValue = r ? `${lead}${r}${trail}` : ' ';
    }
  }
  for (const el of root.querySelectorAll(TR_ATTRS.map((a) => `[${a}]`).join(','))) {
    if (skip(el)) continue;
    for (const a of TR_ATTRS) if (el.hasAttribute(a)) el.setAttribute(a, t(el.getAttribute(a)));
  }
}

